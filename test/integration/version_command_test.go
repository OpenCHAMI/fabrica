// TestVersionCommandNotGeneratedWhenDisabled verifies version command can be disabled
func (s *VersionCommandTestSuite) TestVersionCommandNotGeneratedWhenDisabled() {
	project := s.createProject("version-disabled-test", "github.com/test/version-disabled", "file")

	err := project.InitializeWithFlags(s.fabricaBinary, "--version=false")
	s.Require().NoError(err)

	err = project.AddResource(s.fabricaBinary, "Widget")
	s.Require().NoError(err)

	err = project.Generate(s.fabricaBinary)
	s.Require().NoError(err)

	serverBinary := filepath.Join(project.Dir, "server-binary")
	buildCmd := exec.Command("go", "build", "-o", serverBinary, "./cmd/server")
	buildCmd.Dir = project.Dir
	buildOutput, err := buildCmd.CombinedOutput()
	s.Require().NoError(err, "Server binary should compile successfully: %s", buildOutput)

	cmd := exec.Command(serverBinary, "version")
	cmd.Dir = project.Dir
	output, err := cmd.CombinedOutput()

	s.Require().Error(err, "version command should not exist when disabled")
	s.Require().Contains(string(output), "unknown command", "output should indicate version command doesn't exist")
}

func TestVersionCommandSuite(t *testing.T) {
	suite.Run(t, new(VersionCommandTestSuite))
}
