// emitterFunc adapts a function to ResourceEmitter for tests.
type emitterFunc struct {
	name string
	fn   func(EmitRequest) ([]EmittedFile, error)
}

func (e emitterFunc) Name() string                              { return e.name }
func (e emitterFunc) Emit(r EmitRequest) ([]EmittedFile, error) { return e.fn(r) }

