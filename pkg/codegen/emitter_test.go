// TestEmitterErrorIsWrappedWithResource keeps failures diagnosable.
func TestEmitterErrorIsWrappedWithResource(t *testing.T) {
	gen := newEmitterGenerator(t)

	if err := gen.SetEmitter(EmitterKindEntSchema, emitterFunc{
		name: "test/failing",
		fn: func(EmitRequest) ([]EmittedFile, error) {
			return nil, fmt.Errorf("boom")
		},
	}); err != nil {
		t.Fatalf("SetEmitter failed: %v", err)
	}

	err := gen.GenerateEntSchemas()
	if err == nil {
		t.Fatal("expected the emitter's error to propagate")
	}
	for _, want := range []string{"emitterFixture", "test/failing", "boom"} {
		if !strings.Contains(err.Error(), want) {
			t.Errorf("error %q missing %q", err, want)
		}
	}
}
