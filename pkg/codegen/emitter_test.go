// recordingEmitter stands in for a service-supplied emitter. It captures what
// it was handed so the tests can assert on the contract, and emits an extra
// file alongside the default one.
type recordingEmitter struct {
	mu       sync.Mutex
	calls    []EmitRequest
	extraDir string
}

func (e *recordingEmitter) Name() string { return "test/recording" }

func (e *recordingEmitter) Emit(req EmitRequest) ([]EmittedFile, error) {
	e.mu.Lock()
	e.calls = append(e.calls, req)
	e.mu.Unlock()

	body := fmt.Sprintf(`package %s

// Code generated by the recording emitter for %s.
const %sMarker = %q
`, "schema", req.Resource.Name, req.Resource.Name, req.Annotations.StorageMode)

	files := []EmittedFile{{Path: req.DefaultPath, Content: []byte(body)}}

	if e.extraDir != "" {
		files = append(files, EmittedFile{
			Path:    filepath.Join(e.extraDir, strings.ToLower(req.Resource.Name)+"_extra.go"),
			Content: []byte("package extra\n\n// generated alongside the schema\n"),
		})
	}

	return files, nil
}

func (e *recordingEmitter) requests() []EmitRequest {
	e.mu.Lock()
	defer e.mu.Unlock()

	return append([]EmitRequest(nil), e.calls...)
}

type emitterFixtureSpec struct {
	Value string `json:"value" validate:"required"`
	Owner string `json:"owner"`
}

type emitterFixture struct {
	Spec emitterFixtureSpec
}

// newDedicatedAnnotations builds a valid dedicated-storage annotation set.
func newDedicatedAnnotations() *annotations.ResourceAnnotations {
	a := annotations.NewResourceAnnotations()
	a.IsResource = true
	a.StorageMode = annotations.StorageModeDedicated

	owner := annotations.NewFieldAnnotations("Owner")
	owner.Size = 253
	a.Fields["Owner"] = owner

	return a
}

// newEmitterGenerator returns a generator rooted in a temp dir, with the
// working directory switched for the duration of the test.
func newEmitterGenerator(t *testing.T) *Generator {
	t.Helper()

	tmpDir := t.TempDir()

	origDir, err := os.Getwd()
	if err != nil {
		t.Fatalf("get working directory: %v", err)
	}
	t.Cleanup(func() {
		if err := os.Chdir(origDir); err != nil {
			t.Errorf("restore working directory: %v", err)
		}
	})
	if err := os.Chdir(tmpDir); err != nil {
		t.Fatalf("change to temp directory: %v", err)
	}

	gen := NewGenerator(tmpDir, "test", "github.com/test/project")
	gen.StorageType = "ent"
	gen.DBDriver = "postgres"

	if err := gen.LoadTemplates(); err != nil {
		t.Fatalf("LoadTemplates failed: %v", err)
	}
	if err := gen.RegisterResource(&emitterFixture{}); err != nil {
		t.Fatalf("RegisterResource failed: %v", err)
	}

	gen.SetResourceAnnotations("emitterFixture", newDedicatedAnnotations())

	return gen
}

// TestCustomEmitterIsInvoked is the core claim of the extension point: a
// service can supply its own emitter for a resource and have it run, without
// modifying fabrica's source.
func TestCustomEmitterIsInvoked(t *testing.T) {
	gen := newEmitterGenerator(t)

	emitter := &recordingEmitter{}
	if err := gen.SetEmitter(EmitterKindEntSchema, emitter); err != nil {
		t.Fatalf("SetEmitter failed: %v", err)
	}

	if err := gen.GenerateEntSchemas(); err != nil {
		t.Fatalf("GenerateEntSchemas failed: %v", err)
	}

	reqs := emitter.requests()
	if len(reqs) != 1 {
		t.Fatalf("emitter called %d times, want 1", len(reqs))
	}

	req := reqs[0]
	if req.Kind != EmitterKindEntSchema {
		t.Errorf("Kind = %q, want %q", req.Kind, EmitterKindEntSchema)
	}
	if req.Resource.Name != "emitterFixture" {
		t.Errorf("Resource.Name = %q, want emitterFixture", req.Resource.Name)
	}
	if req.Annotations == nil || req.Annotations.StorageMode != annotations.StorageModeDedicated {
		t.Fatalf("Annotations = %+v, want dedicated storage", req.Annotations)
	}
	if req.Annotations.Fields["Owner"].Size != 253 {
		t.Error("emitter did not receive the resource's field annotations")
	}
	if req.StorageType != "ent" || req.DBDriver != "postgres" {
		t.Errorf("StorageType/DBDriver = %q/%q, want ent/postgres", req.StorageType, req.DBDriver)
	}
	if req.ModulePath != "github.com/test/project" {
		t.Errorf("ModulePath = %q", req.ModulePath)
	}
	if req.Template == nil {
		t.Error("Template is nil; an emitter must be able to reuse the built-in template")
	}
	if req.Data == nil {
		t.Fatal("Data is nil; an emitter must be able to reuse the built-in template data")
	}
	if _, ok := req.Data["CopyrightYear"]; !ok {
		t.Error("Data is missing the merged common fields (CopyrightYear)")
	}

	wantPath := filepath.Join("internal", "storage", "ent", "schema", "emitterfixture.go")
	if req.DefaultPath != wantPath {
		t.Errorf("DefaultPath = %q, want %q", req.DefaultPath, wantPath)
	}

	// The custom output must actually land on disk, replacing the built-in.
	content, err := os.ReadFile(wantPath)
	if err != nil {
		t.Fatalf("read emitted file: %v", err)
	}
	if !strings.Contains(string(content), "emitterFixtureMarker") {
		t.Errorf("emitted file is not the custom emitter's output:\n%s", content)
	}
	if strings.Contains(string(content), "ent.Schema") {
		t.Error("built-in schema was written despite an override being registered")
	}
}

// TestCustomEmitterCanEmitExtraFiles proves an emitter is not limited to
// replacing the default artifact one-for-one.
func TestCustomEmitterCanEmitExtraFiles(t *testing.T) {
	gen := newEmitterGenerator(t)

	if err := gen.SetEmitter(EmitterKindEntSchema, &recordingEmitter{extraDir: "internal/extra"}); err != nil {
		t.Fatalf("SetEmitter failed: %v", err)
	}
	if err := gen.GenerateEntSchemas(); err != nil {
		t.Fatalf("GenerateEntSchemas failed: %v", err)
	}

	extra := filepath.Join("internal", "extra", "emitterfixture_extra.go")
	if _, err := os.Stat(extra); err != nil {
		t.Fatalf("expected the emitter's extra file at %s: %v", extra, err)
	}
}

// TestProcessWideRegistrationIsUsed covers the path a real project takes: an
// init() in a package the generated codegen runner already imports.
func TestProcessWideRegistrationIsUsed(t *testing.T) {
	emitter := &recordingEmitter{}
	if err := RegisterEmitter(EmitterKindEntSchema, emitter); err != nil {
		t.Fatalf("RegisterEmitter failed: %v", err)
	}
	t.Cleanup(func() { UnregisterEmitter(EmitterKindEntSchema) })

	gen := newEmitterGenerator(t)
	if err := gen.GenerateEntSchemas(); err != nil {
		t.Fatalf("GenerateEntSchemas failed: %v", err)
	}

	if got := len(emitter.requests()); got != 1 {
		t.Fatalf("globally registered emitter called %d times, want 1", got)
	}
}

// TestGeneratorEmitterBeatsGlobalRegistration pins the resolution order.
func TestGeneratorEmitterBeatsGlobalRegistration(t *testing.T) {
	global := &recordingEmitter{}
	if err := RegisterEmitter(EmitterKindEntSchema, global); err != nil {
		t.Fatalf("RegisterEmitter failed: %v", err)
	}
	t.Cleanup(func() { UnregisterEmitter(EmitterKindEntSchema) })

	scoped := &recordingEmitter{}

	gen := newEmitterGenerator(t)
	if err := gen.SetEmitter(EmitterKindEntSchema, scoped); err != nil {
		t.Fatalf("SetEmitter failed: %v", err)
	}
	if err := gen.GenerateEntSchemas(); err != nil {
		t.Fatalf("GenerateEntSchemas failed: %v", err)
	}

	if got := len(scoped.requests()); got != 1 {
		t.Errorf("per-generator emitter called %d times, want 1", got)
	}
	if got := len(global.requests()); got != 0 {
		t.Errorf("global emitter called %d times, want 0", got)
	}
}

