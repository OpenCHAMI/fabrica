// TestEmitterProducingInvalidGoFails ensures a broken emitter surfaces a clear
// error instead of writing unparseable source.
func TestEmitterProducingInvalidGoFails(t *testing.T) {
	gen := newEmitterGenerator(t)

	if err := gen.SetEmitter(EmitterKindEntSchema, emitterFunc{
		name: "test/broken",
		fn: func(req EmitRequest) ([]EmittedFile, error) {
			return []EmittedFile{{Path: req.DefaultPath, Content: []byte("this is not go")}}, nil
		},
	}); err != nil {
		t.Fatalf("SetEmitter failed: %v", err)
	}

	err := gen.GenerateEntSchemas()
	if err == nil {
		t.Fatal("expected an error for invalid generated Go")
	}
	if !strings.Contains(err.Error(), "produced invalid Go") {
		t.Errorf("error = %q, want it to mention invalid Go", err)
	}
}

