// TestCustomEmitterCanReuseBuiltinTemplate shows the wrapping case: an emitter
// that renders fabrica's own template and post-processes the result.
func TestCustomEmitterCanReuseBuiltinTemplate(t *testing.T) {
	gen := newEmitterGenerator(t)

	if err := gen.SetEmitter(EmitterKindEntSchema, emitterFunc{
		name: "test/wrapping",
		fn: func(req EmitRequest) ([]EmittedFile, error) {
			base, err := builtinEmitters[EmitterKindEntSchema].Emit(req)
			if err != nil {
				return nil, err
			}
			base[0].Content = append(
				[]byte("// vendor banner\n"),
				base[0].Content...,
			)
			return base, nil
		},
	}); err != nil {
		t.Fatalf("SetEmitter failed: %v", err)
	}

	if err := gen.GenerateEntSchemas(); err != nil {
		t.Fatalf("GenerateEntSchemas failed: %v", err)
	}

	content, err := os.ReadFile(filepath.Join("internal", "storage", "ent", "schema", "emitterfixture.go"))
	if err != nil {
		t.Fatalf("read generated schema: %v", err)
	}
	got := string(content)
	if !strings.HasPrefix(got, "// vendor banner") {
		t.Errorf("wrapper banner missing:\n%s", got)
	}
	if !strings.Contains(got, "ent.Schema") {
		t.Errorf("wrapped built-in output missing:\n%s", got)
	}
}

// TestDocumentedDelegatingEmitter exercises the exact pattern documented in
// docs/reference/codegen.md: customize the resources you care about, hand the
// rest back to the built-in via BuiltinEmitter.
func TestDocumentedDelegatingEmitter(t *testing.T) {
	delegating := emitterFunc{
		name: "test/delegating",
		fn: func(req EmitRequest) ([]EmittedFile, error) {
			files, err := BuiltinEmitter(req.Kind).Emit(req)
			if err != nil {
				return nil, err
			}
			if req.Annotations.Migration != annotations.MigrationPolicyAdditiveOnly {
				return files, nil
			}
			banner := fmt.Sprintf("// AUDITED SCHEMA — %s is append-only.\n", req.Resource.Name)
			files[0].Content = append([]byte(banner), files[0].Content...)

			return files, nil
		},
	}

	t.Run("delegates when the resource does not opt in", func(t *testing.T) {
		gen := newEmitterGenerator(t)
		if err := gen.SetEmitter(EmitterKindEntSchema, delegating); err != nil {
			t.Fatalf("SetEmitter failed: %v", err)
		}
		if err := gen.GenerateEntSchemas(); err != nil {
			t.Fatalf("GenerateEntSchemas failed: %v", err)
		}

		content, err := os.ReadFile(filepath.Join("internal", "storage", "ent", "schema", "emitterfixture.go"))
		if err != nil {
			t.Fatalf("read generated schema: %v", err)
		}
		if strings.Contains(string(content), "AUDITED SCHEMA") {
			t.Error("banner applied to a resource that did not opt in")
		}
		if !strings.Contains(string(content), "ent.Schema") {
			t.Error("delegated output is not the built-in schema")
		}
	})

	t.Run("customizes when the resource opts in", func(t *testing.T) {
		gen := newEmitterGenerator(t)

		annots := newDedicatedAnnotations()
		annots.Migration = annotations.MigrationPolicyAdditiveOnly
		gen.SetResourceAnnotations("emitterFixture", annots)

		if err := gen.SetEmitter(EmitterKindEntSchema, delegating); err != nil {
			t.Fatalf("SetEmitter failed: %v", err)
		}
		if err := gen.GenerateEntSchemas(); err != nil {
			t.Fatalf("GenerateEntSchemas failed: %v", err)
		}

		content, err := os.ReadFile(filepath.Join("internal", "storage", "ent", "schema", "emitterfixture.go"))
		if err != nil {
			t.Fatalf("read generated schema: %v", err)
		}
		got := string(content)
		if !strings.HasPrefix(got, "// AUDITED SCHEMA") {
			t.Errorf("banner missing:\n%s", got)
		}
		if !strings.Contains(got, "ent.Schema") {
			t.Errorf("built-in output missing:\n%s", got)
		}
	})
}

